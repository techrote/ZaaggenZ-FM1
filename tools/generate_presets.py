#!/usr/bin/env python3
"""Compile the reviewed preset recipes and fixed pitch tables; no runtime float."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    recipes = json.loads((ROOT / "presets/factory.json").read_text())
    rows = ['/* Generated by tools/generate_presets.py; SPDX-License-Identifier: MIT */',
            '#include "zg/engine.h"', 'const zg_preset zg_presets[] = {']
    for r in recipes:
        p = r['patch']
        vals = [str(p[k]) for k in ['family', 'source', 'mode', 'grit', 'motion', 'vowel']]
        vals += ['{' + ','.join(map(str, p['level'])) + '}']
        vals += [str(p[k]) for k in ['attack', 'decay', 'sustain', 'release', 'glide',
                'roll', 'tuning', 'sub_mode', 'body_degree', 'aux_degree',
                'separation', 'gain', 'quality', 'source_sustain', 'bypass', 'bpm']]
        rows.append('  {' + json.dumps(r['name']) + ', ' + json.dumps(r['description']) +
                    ', {' + ', '.join(vals) + '}},')
    rows += ['};', 'const unsigned zg_preset_count = sizeof(zg_presets)/sizeof(zg_presets[0]);',
             'const char *const zg_preset_names[] = {']
    rows += ['  '+json.dumps(r['name'])+',' for r in recipes]
    rows += ['  0', '};', '']
    pitch = ['/* Generated fixed phase increments at 44100 Hz. SPDX-License-Identifier: MIT */',
             'static const uint32_t PITCH_TABLE[4][128] = {']
    for steps, period in [(12, 2), (19, 2), (24, 2), (13, 3)]:
        vals = [round(130.8127826502993 * period ** ((k - 48) / steps) * 2**32 / 44100) for k in range(128)]
        vals = [min(v, 0x73333333) for v in vals]  # cap at .45 Fs
        pitch += ['  {'] + ['    ' + ', '.join(str(v)+'u' for v in vals[i:i+8]) + ',' for i in range(0,128,8)] + ['  },']
    pitch += ['};', '']
    pitch += ['static const uint32_t BEND_RATIO_Q20[401] = {']
    bend=[round(2**(c/1200)*2**20) for c in range(-200,201)]
    pitch += ['  '+', '.join(str(v)+'u' for v in bend[i:i+8])+',' for i in range(0,len(bend),8)]
    pitch += ['};','']
    return {ROOT / 'src/presets.c': '\n'.join(rows), ROOT / 'src/pitch_tables.inc': '\n'.join(pitch)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'{path.name} is stale; run tools/generate_presets.py')
        else:
            path.write_text(text)
