#!/usr/bin/env python3
"""Generate deterministic mathematical Q15 tables; no upstream source copied."""
from pathlib import Path
import math
import argparse

def emit(name, vals, columns=12):
    rows = [', '.join(str(x) for x in vals[i:i+columns]) for i in range(0,len(vals),columns)]
    return 'static const int16_t '+name+'['+str(len(vals))+'] = {\n    '+',\n    '.join(rows)+'\n};\n'

def generate():
    text='/* SPDX-License-Identifier: MIT\n * Generated by tools/gen_dsp_tables.py; do not edit. */\n'
    text+=emit('zg_sine_table',[round(math.sin(2*math.pi*i/1024)*32767) for i in range(1025)])
    text+=emit('zg_tanh_table',[round(math.tanh(i/64)*32767) for i in range(257)])
    # Legacy family lattice: harmonic exponent, parity, spectral tilt. Bounded
    # 16-partial native implementation; normalization is fixed from coefficients.
    profiles=[(.55,1.9,-.25),(.5,2.15,-.25),(.57,1.9,-.25),(.66,2.4,-.25),(.5,1.9,-.25),(.44,2.2,.15)]
    for f,(decay,parity,tilt) in enumerate(profiles):
        w=[k**(-decay)*(1 if k%2 else 1/parity)*10**(tilt*math.log2(k)/20) for k in range(1,17)]
        # 0.75 peak for an exactly aligned lattice; no rendered-data normalization.
        text+=emit('zg_weights_'+str(f),[round(v/sum(w)*24576) for v in w])
    text+='static const int16_t * const zg_weights[6] = {'+', '.join('zg_weights_'+str(f) for f in range(6))+'};\n'
    return text

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    path=Path(__file__).resolve().parents[1]/'src'/'dsp_tables.inc';text=generate()
    if a.check:
        if path.read_text()!=text: raise SystemExit('DSP tables are stale')
    else: path.write_text(text)
